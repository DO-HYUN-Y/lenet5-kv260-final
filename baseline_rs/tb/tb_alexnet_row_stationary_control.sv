 task automatic wr(input integer address,input logic[31:0] value);
   @(negedge aclk);s_axi_ctrl_awaddr=8'(address);s_axi_ctrl_awvalid=1;
   do @(posedge aclk);while(!s_axi_ctrl_awready);
   @(negedge aclk);s_axi_ctrl_awvalid=0;
   repeat(2) @(negedge aclk);s_axi_ctrl_wdata=value;s_axi_ctrl_wvalid=1;
   do @(posedge aclk);while(!s_axi_ctrl_wready);
   @(negedge aclk);s_axi_ctrl_wvalid=0;s_axi_ctrl_bready=1;
   do @(posedge aclk);while(!s_axi_ctrl_bvalid);
   if(s_axi_ctrl_bresp!=0) $fatal(1,"write response");
   @(negedge aclk);s_axi_ctrl_bready=0;
 endtask
 task automatic rd(input integer address,input logic[31:0] expected,input logic[1:0] response=0);
   logic[31:0] held;logic[1:0] held_resp;
   @(negedge aclk);s_axi_ctrl_araddr=8'(address);s_axi_ctrl_arvalid=1;s_axi_ctrl_rready=0;
   do @(posedge aclk);while(!s_axi_ctrl_arready);
   @(negedge aclk);s_axi_ctrl_arvalid=0;
   wait(s_axi_ctrl_rvalid);held=s_axi_ctrl_rdata;held_resp=s_axi_ctrl_rresp;
   repeat(5) begin
     @(negedge aclk);
     if(!s_axi_ctrl_rvalid || s_axi_ctrl_rdata!==held || s_axi_ctrl_rresp!==held_resp) $fatal(1,"stalled CSR response changed");
   end
   if(held!==expected || held_resp!==response) $fatal(1,"CSR %h got=%h expected=%h response=%d",address,held,expected,held_resp);
   s_axi_ctrl_rready=1;@(posedge aclk);@(negedge aclk);s_axi_ctrl_rready=0;
 endtask
