   repeat(6) @(negedge aclk);aresetn=1;
   // Isolate control/telemetry from computation; the real core and DMA paths
   // are exercised by the separate trained-core and DDR engine regressions.
   force dut.core_start_ready=1'b1;force dut.engine_busy=1'b0;force dut.engine_done=1'b0;force dut.engine_fault=1'b0;
   force dut.main_read_axis_bytes=64'd100;force dut.main_write_axis_bytes=64'd50;
   force dut.weight_service_bytes=64'd1000;force dut.gather_requested_bytes=64'd80;
   force dut.useful_mac_count=64'd500;force dut.stored_packets=32'd5;
   force dut.main_completed_transfers=32'd9;force dut.completed_commands=32'd0;force dut.completed_input_tiles=32'd0;
   rd('h00,32'h52530100);rd('h7c,32'h088000c8);rd('hb0,100);rd('hec,0,2'b10);rd('hb1,0,2'b10);
   for(int a='h10;a<='h38;a+=8) begin wr(a,32'h00100000+32'(a)*128);wr(a+4,0);end
   wr('h0c,1);wr('h04,1);repeat(5) @(negedge aclk);
